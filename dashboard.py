# DATA VALIDATION
# ============================================================

def validate_data(df):

    print()
    print("=" * 60)
    print("DATA VALIDATION")
    print("=" * 60)

    if df.empty:

        print(
            "ERROR: Dataset is empty."
        )

        return False

    required_columns = [
        "id",
        "type",
        "model",
        "status",
        "lost_by",
        "date"
    ]

    missing_columns = [
        column
        for column in required_columns
        if column not in df.columns
    ]

    if missing_columns:

        print(
            "Missing columns:"
        )

        print(
            missing_columns
        )

        return False

    duplicate_ids = (
        df["id"]
        .duplicated()
        .sum()
    )

    print(
        f"Records       : "
        f"{len(df):,}"
    )

    print(
        f"Unique IDs    : "
        f"{df['id'].nunique():,}"
    )

    print(
        f"Duplicate IDs : "
        f"{duplicate_ids:,}"
    )

    print(
        f"First date    : "
        f"{df['date'].min().date()}"
    )

    print(
        f"Last date     : "
        f"{df['date'].max().date()}"
    )

    # --------------------------------------------------------
    # Validation result.
    # --------------------------------------------------------

    if duplicate_ids > 0:

        print()
        print(
            "VALIDATION: FAILED"
        )

        return False

    print()
    print(
        "VALIDATION: OK"
    )

    return True


