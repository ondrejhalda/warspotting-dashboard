import os
import time
from datetime import date, timedelta

import requests
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.dates as mdates


# ============================================================
# WARSPOTTING – AUTOMATED DATA ANALYSIS DASHBOARD
# ============================================================

BASE_URL = "https://ukr.warspotting.net/api/losses/russia"

RAW_FILE = "warspotting_raw_2026.csv"
WEEKLY_FILE = "weekly_losses_2026.csv"
DASHBOARD_FILE = "dashboard.png"

START_DATE = date(2026, 1, 1)


# ============================================================
# API SETTINGS
# ============================================================

HEADERS = {
    "User-Agent": "WarSpotting-Analytics-Dashboard/1.0"
}

MAX_RETRIES = 5
RETRY_DELAY = 5


# ============================================================
# API REQUEST
# ============================================================

def get_day_data(target_date):
    """
    Download WarSpotting losses for one day.
    Includes retry logic for temporary API errors.
    """

    date_string = target_date.strftime("%Y-%m-%d")

    url = f"{BASE_URL}/{date_string}/1/"

    for attempt in range(1, MAX_RETRIES + 1):

        try:

            response = requests.get(
                url,
                headers=HEADERS,
                timeout=30
            )

            if response.status_code == 200:

                data = response.json()

                if isinstance(data, dict):

                    return data.get("losses", [])

                return []

            if response.status_code in [
                429,
                500,
                502,
                503,
                504,
                520
            ]:

                wait = RETRY_DELAY * attempt

                print(
                    f"HTTP {response.status_code} | "
                    f"{date_string} | "
                    f"retry {attempt}/{MAX_RETRIES} "
                    f"in {wait}s"
                )

                time.sleep(wait)

                continue

            print(
                f"HTTP {response.status_code} | "
                f"{date_string}"
            )

            return []

        except requests.RequestException as error:

            wait = RETRY_DELAY * attempt

            print(
                f"REQUEST ERROR | "
                f"{date_string} | "
                f"retry {attempt}/{MAX_RETRIES} "
                f"in {wait}s"
            )

            time.sleep(wait)

    print(
        f"FAILED: {date_string}"
    )

    return []


# ============================================================
# LOAD EXISTING RAW DATA
# ============================================================

def load_existing_data():

    if not os.path.exists(RAW_FILE):

        print()
        print("=" * 60)
        print("NO EXISTING DATASET")
        print("=" * 60)

        return pd.DataFrame()

    print()
    print("=" * 60)
    print("EXISTING DATASET")
    print("=" * 60)

    df = pd.read_csv(RAW_FILE)

    df["date"] = pd.to_datetime(
        df["date"]
    )

    print(
        f"Records loaded : {len(df):,}"
    )

    if len(df) > 0:

        print(
            f"First date     : "
            f"{df['date'].min().date()}"
        )

        print(
            f"Last date      : "
            f"{df['date'].max().date()}"
        )

    return df


# ============================================================
# UPDATE RAW DATA
# ============================================================

def update_raw_data(df):

    yesterday = (
        pd.Timestamp.today().normalize()
        - pd.Timedelta(days=1)
    )

    # --------------------------------------------------------
    # Determine first date that needs to be downloaded.
    # --------------------------------------------------------

    if df.empty:

        start_date = pd.Timestamp(
            START_DATE
        )

    else:

        last_date = df["date"].max()

        start_date = (
            last_date
            + pd.Timedelta(days=1)
        )

    # --------------------------------------------------------
    # Dataset already up to date.
    # --------------------------------------------------------

    if start_date > yesterday:

        print()
        print(
            "RAW DATA ALREADY UP TO DATE"
        )

        return df

    print()
    print("=" * 60)
    print("DOWNLOADING NEW DATA")
    print("=" * 60)

    print(
        f"From: {start_date.date()}"
    )

    print(
        f"To:   {yesterday.date()}"
    )

    new_records = []

    current_date = start_date

    # --------------------------------------------------------
    # Download one day at a time.
    # --------------------------------------------------------

    while current_date <= yesterday:

        records = get_day_data(
            current_date.date()
        )

        print(
            f"{current_date.date()} | "
            f"records: {len(records)}"
        )

        new_records.extend(
            records
        )

        current_date += pd.Timedelta(
            days=1
        )

        # Prevent excessive API requests.
        time.sleep(1.5)

    # --------------------------------------------------------
    # Add new data to existing dataset.
    # --------------------------------------------------------

    if new_records:

        new_df = pd.DataFrame(
            new_records
        )

        new_df["date"] = pd.to_datetime(
            new_df["date"]
        )

        if df.empty:

            df = new_df

        else:

            df = pd.concat(
                [df, new_df],
                ignore_index=True
            )

        # ----------------------------------------------------
        # Remove duplicate equipment records.
        # ----------------------------------------------------

        before = len(df)

        df = df.drop_duplicates(
            subset=["id"],
            keep="last"
        )

        duplicates_removed = (
            before - len(df)
        )

        # ----------------------------------------------------
        # Sort chronologically.
        # ----------------------------------------------------

        df = df.sort_values(
            ["date", "id"]
        ).reset_index(
            drop=True
        )

        # ----------------------------------------------------
        # Save RAW dataset.
        # ----------------------------------------------------

        df.to_csv(
            RAW_FILE,
            index=False
        )

        print()
        print(
            f"New records added : "
            f"{len(new_records):,}"
        )

        print(
            f"Duplicates removed: "
            f"{duplicates_removed:,}"
        )

        print(
            f"Total records     : "
            f"{len(df):,}"
        )

        print(
            f"RAW DATA SAVED    : "
            f"{RAW_FILE}"
        )

    else:

        print()
        print(
            "No new records downloaded."
        )

    return df


