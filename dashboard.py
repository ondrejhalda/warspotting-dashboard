def create_dashboard(df, weekly):

    # --------------------------------------------------------
    # KPI calculations
    # --------------------------------------------------------

    total_losses = len(df)

    this_week = int(
        weekly.iloc[-1][
            "weekly_losses"
        ]
    )

    four_week_avg = float(
        weekly.iloc[-1][
            "rolling_4_week_avg"
        ]
    )

    # --------------------------------------------------------
    # Data quality check.
    # --------------------------------------------------------

    weekly_total = int(
        weekly["weekly_losses"].sum()
    )

    data_check = (
        total_losses == weekly_total
    )

    # --------------------------------------------------------
    # Console summary.
    # --------------------------------------------------------

    print()
    print("=" * 60)
    print("WARSPOTTING DASHBOARD")
    print("=" * 60)

    print(
        f"TOTAL LOSSES : "
        f"{total_losses:,}"
    )

    print(
        f"THIS WEEK    : "
        f"{this_week}"
    )

    print(
        f"4-WEEK AVG   : "
        f"{four_week_avg:.1f}"
    )

    print(
        f"DATA CHECK   : "
        f"{'OK' if data_check else 'ERROR'}"
    )

    if not data_check:

        raise ValueError(
            "Weekly totals do not match "
            "RAW dataset."
        )

    # ========================================================
    # FIGURE
    # ========================================================

    fig = plt.figure(
        figsize=(16, 9)
    )

    # --------------------------------------------------------
    # Dashboard title
    # --------------------------------------------------------

    fig.text(
        0.055,
        0.955,
        "WarSpotting – Russian Equipment Losses Dashboard",
        fontsize=24,
        fontweight="bold",
        ha="left"
    )

    # ========================================================
    # KPI CARDS
    # ========================================================

    cards = [
        (
            0.055,
            "TOTAL LOSSES",
            f"{total_losses:,}"
        ),
        (
            0.375,
            "THIS WEEK",
            f"{this_week:,}"
        ),
        (
            0.695,
            "4-WEEK AVG",
            f"{four_week_avg:.1f}"
        )
    ]

    for x, label, value in cards:

        ax_card = fig.add_axes(
            [
                x,
                0.72,
                0.27,
                0.15
            ]
        )

        ax_card.set_xticks([])
        ax_card.set_yticks([])

        for spine in ax_card.spines.values():

            spine.set_visible(True)
            spine.set_linewidth(1)

        ax_card.text(
            0.06,
            0.70,
            label,
            fontsize=12,
            fontweight="bold",
            transform=ax_card.transAxes
        )

        ax_card.text(
            0.06,
            0.20,
            value,
            fontsize=28,
            fontweight="bold",
            transform=ax_card.transAxes
        )

    # ========================================================
    # MAIN CHART
    # ========================================================

    ax = fig.add_axes(
        [
            0.055,
            0.12,
            0.90,
            0.50
        ]
    )

    weeks = weekly["week"]

    weekly_losses = (
        weekly["weekly_losses"]
    )

    cumulative_losses = (
        weekly["cumulative_losses"]
    )

    # --------------------------------------------------------
    # WEEKLY LOSSES – BARS
    # --------------------------------------------------------

    ax.bar(
        weeks,
        weekly_losses,
        width=5.5,
        alpha=0.85,
        label="Weekly losses"
    )

    # --------------------------------------------------------
    # CUMULATIVE LOSSES – LINE
    # --------------------------------------------------------

    ax2 = ax.twinx()

    ax2.plot(
        weeks,
        cumulative_losses,
        linewidth=1.5,
        alpha=0.75,
        label="Cumulative losses"
    )

    # --------------------------------------------------------
    # Titles
    # --------------------------------------------------------

    ax.set_title(
        "Russian Equipment Losses Over Time",
        fontsize=18,
        fontweight="bold",
        loc="left",
        pad=14
    )

    # --------------------------------------------------------
    # Axis labels
    # --------------------------------------------------------

    ax.set_ylabel(
        "Weekly recorded losses",
        fontsize=11
    )

    ax2.set_ylabel(
        "Cumulative recorded losses",
        fontsize=11
    )

    ax.set_xlabel(
        "Week",
        fontsize=11
    )

    # ========================================================
    # ADAPTIVE Y AXIS
    # ========================================================

    max_weekly = (
        weekly_losses.max()
    )

    y_max = max(
        10,
        ((max_weekly * 1.15) // 5 + 1) * 5
    )

    ax.set_ylim(
        0,
        y_max
    )

    # ========================================================
    # ADAPTIVE X AXIS
    #
    # Every bar = one week.
    # Major labels approximately every 2 months.
    # ========================================================

    ax.xaxis.set_major_locator(
        mdates.MonthLocator(
            interval=2
        )
    )

    ax.xaxis.set_major_formatter(
        mdates.DateFormatter(
            "%b %Y"
        )
    )

    # --------------------------------------------------------
    # X-axis limits
    # --------------------------------------------------------

    ax.set_xlim(
        weeks.min()
        - pd.Timedelta(days=7),

        weeks.max()
        + pd.Timedelta(days=14)
    )

    # --------------------------------------------------------
    # Grid
    # --------------------------------------------------------

    ax.grid(
        axis="y",
        alpha=0.25
    )

    ax.set_axisbelow(True)

    # --------------------------------------------------------
    # Remove unnecessary borders.
    # --------------------------------------------------------

    ax.spines["top"].set_visible(
        False
    )

    ax2.spines["top"].set_visible(
        False
    )

    # ========================================================
    # LEGEND
    # ========================================================

    bars, labels = ax.get_legend_handles_labels()

    lines, line_labels = (
        ax2.get_legend_handles_labels()
    )

    ax.legend(
        bars + lines,
        labels + line_labels,
        loc="upper left"
    )

    # ========================================================
    # SAVE DASHBOARD
    # ========================================================

    plt.savefig(
        DASHBOARD_FILE,
        dpi=150,
        bbox_inches="tight"
    )

    plt.close(fig)

    print()
    print("=" * 60)
    print("DASHBOARD CREATED")
    print("=" * 60)

    print(
        f"File: {DASHBOARD_FILE}"
    )

    return (
        total_losses,
        this_week,
        four_week_avg
    )


