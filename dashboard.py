# ============================================================

def create_weekly_dataset(df):

    print()
    print("=" * 60)
    print("WEEKLY ANALYSIS")
    print("=" * 60)

    data = df.copy()

    data["date"] = pd.to_datetime(
        data["date"]
    )

    # --------------------------------------------------------
    # Monday = beginning of analytical week.
    # --------------------------------------------------------

    data["week"] = (
        data["date"]
        - pd.to_timedelta(
            data["date"].dt.weekday,
            unit="D"
        )
    )

    # --------------------------------------------------------
    # Count records per week.
    # --------------------------------------------------------

    weekly = (
        data
        .groupby("week")
        .size()
        .reset_index(
            name="weekly_losses"
        )
    )

    weekly = weekly.sort_values(
        "week"
    ).reset_index(
        drop=True
    )

    # --------------------------------------------------------
    # Cumulative losses.
    # --------------------------------------------------------

    weekly["cumulative_losses"] = (
        weekly["weekly_losses"]
        .cumsum()
    )

    # --------------------------------------------------------
    # Four-week moving average.
    # --------------------------------------------------------

    weekly["rolling_4_week_avg"] = (
        weekly["weekly_losses"]
        .rolling(
            window=4,
            min_periods=1
        )
        .mean()
    )

    # --------------------------------------------------------
    # Save analytical dataset.
    # --------------------------------------------------------

    weekly.to_csv(
        WEEKLY_FILE,
        index=False
    )

    print(
        f"Number of weeks : "
        f"{len(weekly)}"
    )

    print(
        f"First week      : "
        f"{weekly['week'].min().date()}"
    )

    print(
        f"Last week       : "
        f"{weekly['week'].max().date()}"
    )

    print()
    print(
        "Last 10 weeks:"
    )

    print(
        weekly.tail(10).to_string(
            index=False
        )
    )

    print()
    print(
        f"WEEKLY DATA SAVED: "
        f"{WEEKLY_FILE}"
    )

    return weekly


