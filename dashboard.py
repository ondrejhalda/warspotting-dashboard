    # --------------------------------------------------------

    weekly = create_weekly_dataset(
        df
    )

    # --------------------------------------------------------
    # 5. Create dashboard.
    # --------------------------------------------------------

    create_dashboard(
        df,
        weekly
    )

    # --------------------------------------------------------
    # 6. Final status.
    # --------------------------------------------------------

    print()
    print("=" * 60)
    print("PIPELINE COMPLETE")
    print("=" * 60)

    print(
        "STATUS: OK"
    )


