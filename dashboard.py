def main():

    print()
    print("=" * 60)
    print("WARSPOTTING AUTOMATED PIPELINE")
    print("=" * 60)

    # --------------------------------------------------------
    # 1. Load existing RAW dataset.
    # --------------------------------------------------------

    df = load_existing_data()

    # --------------------------------------------------------
    # 2. Download only new data.
    # --------------------------------------------------------

    df = update_raw_data(
        df
    )

    # --------------------------------------------------------
    # 3. Validate RAW dataset.
    # --------------------------------------------------------

